export function getHmcCountry(code: string | null | undefined): HmcCountryConfig | undefined {
  const k = (code ?? '').trim().toUpperCase();
  return HMC_COUNTRIES.find((c) => c.code === k);
}

export function getHmcRegionsForCountry(countryCode: string | null | undefined): ReadonlyArray<HmcRegionOption> {
  const k = (countryCode ?? '').trim().toUpperCase();
  return HMC_REGIONS_BY_COUNTRY[k] ?? [];
}

/** Resolve region abbrev → ISO country (US wins collisions). */
export function hmcCountryForRegion(regionAbbrev: string | null | undefined): string | null {
  const k = (regionAbbrev ?? '').trim().toUpperCase();
  return REGION_TO_COUNTRY[k] ?? null;
}

/** Normalize HMC region abbrev if known, else null. */
export function normalizeHmcRegionCode(region: string | null | undefined): string | null {
  const k = (region ?? '').trim().toUpperCase();
  if (!k || !REGION_TO_COUNTRY[k]) return null;
  return k;
}

export function isHmcDirectoryCountry(code: string | null | undefined): boolean {
  return getHmcCountry(code) != null;
}

/** True when value is an HMC ISO code or an exact directory country name. */
export function matchesHmcDirectoryCountry(value: string | null | undefined): boolean {
  const raw = (value ?? '').trim();
  if (!raw) return false;
  if (getHmcCountry(raw)) return true;
  const lower = raw.toLowerCase();
  return HMC_COUNTRIES.some((c) => c.name.toLowerCase() === lower);
}

/**
 * Map Nominatim / free-text place hints to an HMC region abbrev within a country.
 * Prefers ISO3166-2 (`US-TX`, `CA-ON`), then state_code, then region display name.
 */
export function matchHmcRegionInCountry(
  countryCode: string | null | undefined,
  hints: {
    iso3166?: string | null;
    stateCode?: string | null;
    stateName?: string | null;
  },
): string | null {
  const cc = (countryCode ?? '').trim().toUpperCase();
  if (!cc || !HMC_COUNTRY_CODES.has(cc)) return null;
  const regions = getHmcRegionsForCountry(cc);

  const iso = (hints.iso3166 ?? '').trim().toUpperCase();
  if (iso) {
    const parts = iso.split('-');
    if (parts.length >= 2) {
      const isoCc = parts[0]!;
      const isoRegion = parts.slice(1).join('-');
      if (isoCc === cc) {
        const byCode = normalizeHmcRegionCode(isoRegion);
        if (byCode && hmcCountryForRegion(byCode) === cc) return byCode;
        // Some HMC abbrevs are the full ISO tail (AUNSW, GREATERLONDON).
        const direct = regions.find((r) => r.code === isoRegion);
        if (direct) return direct.code;
      }
    }
  }

  const stateCode = (hints.stateCode ?? '').trim().toUpperCase();
  if (stateCode) {
    const byCode = normalizeHmcRegionCode(stateCode);
    if (byCode && hmcCountryForRegion(byCode) === cc) return byCode;
    const inCountry = regions.find((r) => r.code === stateCode);
    if (inCountry) return inCountry.code;
  }

  const stateName = (hints.stateName ?? '').trim().toLowerCase();
  if (stateName) {
    const exact = regions.find((r) => r.label.toLowerCase() === stateName);
    if (exact) return exact.code;
    const starts = regions.find(
      (r) => stateName.startsWith(r.label.toLowerCase()) || r.label.toLowerCase().startsWith(stateName),
    );
    if (starts) return starts.code;
  }

  return null;
}
