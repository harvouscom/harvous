#!/usr/bin/env node

/**
 * Generates public/scripts/prototype-image-presets-catalog.js from
 * shared/appearance-image-presets.json for synchronous first-paint boot.
 *
 * Keep parsing/resolution in sync with spa/src/lib/prototype-background.ts
 * and public/scripts/prototype-route-boot.js.
 */

import { readFileSync, writeFileSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
const catalogPath = join(root, 'shared', 'appearance-image-presets.json');
const outPath = join(root, 'public', 'scripts', 'prototype-image-presets-catalog.js');

const catalog = JSON.parse(readFileSync(catalogPath, 'utf8'));
const payload = JSON.stringify(catalog);

const output = `/**
 * AUTO-GENERATED by scripts/sync-appearance-image-presets.js — do not edit.
 * Source: shared/appearance-image-presets.json
 */
window.__HARVOUS_APPEARANCE_IMAGE_PRESETS = ${payload};
`;

writeFileSync(outPath, output);
console.log('sync-appearance-image-presets: wrote', outPath);
